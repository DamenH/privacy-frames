#!/usr/bin/env python3
"""Generate the finite registry transition graph from TLC, not a hand-coded oracle."""
import hashlib
import json
import re
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[2]
directory = root / 'formal/confinement'
jar = root / '.tools/tla2tools.jar'
assert hashlib.sha256(jar.read_bytes()).hexdigest() == '011267fca25d0752cf18894dd585cd28b96960c112ea8a20b823ea770e7e10cd'
image = 'eclipse-temurin:21-jre@sha256:0b99b3376fbb50dbf9c0af8535fdd5b8eb0d3fdfc8b1e4967f383b6919f6901a'
command = ('java -cp /work/.tools/tla2tools.jar tlc2.TLC -workers 1 '
           '-metadir /tmp/states -noGenerateSpecTE -dump dot,actionlabels /tmp/registry.dot '
           '-config /work/formal/confinement/RegistrySafe.cfg '
           '/work/formal/confinement/Registry.tla >/dev/null && cat /tmp/registry.dot')
dot = subprocess.check_output(['docker', 'run', '--rm', '--network', 'none', '-v',
                               f'{root}:/work:ro', '-w', '/tmp', image, 'sh', '-c', command], text=True)
nodes, edges = {}, []
for line in dot.splitlines():
    node = re.match(r'^(-?\d+) \[label="((?:\\.|[^"\\])*)"', line)
    edge = re.match(r'^(-?\d+) -> (-?\d+) \[label="([^" ]+)', line)
    if node:
        label = json.loads('"' + node.group(2) + '"')
        fields = dict(re.findall(r'/\\ (\w+) = ("[^"]*"|TRUE|FALSE)', label))
        if set(fields) != {'state', 'closedByOwner', 'closedByOther', 'badBind', 'badRevive', 'badClose'}:
            raise ValueError(label)
        nodes[node.group(1)] = {k: json.loads(v) if v.startswith('"') else v == 'TRUE' for k, v in fields.items()}
    if edge:
        edges.append({'from': edge.group(1), 'to': edge.group(2), 'action': edge.group(3)})
assert nodes and edges and all(e['from'] in nodes and e['to'] in nodes for e in edges)
receipt = {'scope': 'TLC finite registry graph; atomic storage and single identity abstraction',
           'inputs': {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in [directory/'Registry.tla', directory/'RegistrySafe.cfg']},
           'nodes': nodes, 'edges': edges}
(directory / 'registry-graph.json').write_text(json.dumps(receipt, indent=2) + '\n')
print(f'{len(nodes)} states, {len(edges)} transitions generated by TLC')
